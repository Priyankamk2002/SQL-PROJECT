-- 1️. Customer Insights

-- HOW MANY UNIQUE CUSTOMERS HAVE PLACED ORDERS?
select count(distinct cust_id) as UNIQUE_CUSTOMERS 
from orders;

-- WHICH CUSTOMERS HAVE PLACED THE HIGHEST NUMBER OF ORDERS?
SELECT 
    c.cust_id, c.cust_name, COUNT(o.ord_id) AS total_orders
FROM
    customers c
        JOIN
    orders o ON c.cust_id = o.cust_id
GROUP BY c.cust_id , c.cust_name
ORDER BY total_orders DESC
LIMIT 1;

-- Total and average purchase value per customer
SELECT 
    c.cust_id,
    c.cust_name,
    SUM(od.total_price) AS total_purchase,
    AVG(od.total_price) AS average_purchase
FROM customers c
JOIN orders o ON c.cust_id = o.cust_id
JOIN order_details od ON o.ord_id = od.ord_id
GROUP BY c.cust_id, c.cust_name
ORDER BY total_purchase DESC;

