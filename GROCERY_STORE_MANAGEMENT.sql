-- 2. Product Performance

-- How many products exist in each category?
SELECT 
    c.cat_id, c.cat_name, COUNT(p.prod_id) AS num_products
FROM
    categories c
        LEFT JOIN
    products p ON c.cat_id = p.cat_id
GROUP BY c.cat_id , c.cat_name
ORDER BY num_products DESC;

-- What is the average price of products by category?

SELECT 
    c.cat_id,
    c.cat_name,
    AVG(p.price) AS avg_price
FROM categories c
JOIN products p ON c.cat_id = p.cat_id
GROUP BY c.cat_id, c.cat_name
ORDER BY avg_price DESC;

-- Which products have the highest total sales volume (by quantity)?
SELECT 
    p.prod_id,
    p.prod_name,
    SUM(od.quantity) AS total_quantity_sold
FROM products p
JOIN order_details od ON p.prod_id = od.prod_id
GROUP BY p.prod_id, p.prod_name
ORDER BY total_quantity_sold DESC
LIMIT 10;

-- What is the total revenue generated by each product?

SELECT 
    p.prod_id,
    p.prod_name,
    SUM(od.total_price) AS total_revenue
FROM products p
JOIN order_details od ON p.prod_id = od.prod_id
GROUP BY p.prod_id, p.prod_name
ORDER BY total_revenue DESC
LIMIT 10;

-- How do product sales vary by category and supplier?
SELECT 
    c.cat_name,
    s.sup_name,
    SUM(od.quantity) AS total_quantity_sold,
    SUM(od.total_price) AS total_revenue
FROM products p
JOIN categories c ON p.cat_id = c.cat_id
JOIN supplier s ON p.sup_id = s.sup_id
JOIN order_details od ON p.prod_id = od.prod_id
GROUP BY c.cat_name, s.sup_name
ORDER BY c.cat_name, total_revenue DESC;

-- 3.SALES AND ORDER TRENDS
-- How many orders have been placed in total?
SELECT COUNT(*) AS total_orders
FROM orders;

-- What is the average value per order?
SELECT 
    o.ord_id,
    SUM(od.total_price) AS order_total
FROM orders o
JOIN order_details od ON o.ord_id = od.ord_id
GROUP BY o.ord_id
ORDER BY order_total DESC;

-- On which dates were the most orders placed?
SELECT 
    order_date,
    COUNT(ord_id) AS orders_count
FROM orders
GROUP BY order_date
ORDER BY orders_count DESC
LIMIT 5;

-- Monthly trends in order volume and revenue
SELECT 
    DATE_FORMAT(STR_TO_DATE(order_date, '%Y-%m-%d'), '%Y-%m') AS order_month,
    COUNT(o.ord_id) AS total_orders,
    SUM(od.total_price) AS total_revenue
FROM orders o
JOIN order_details od ON o.ord_id = od.ord_id
GROUP BY order_month
ORDER BY order_month;

-- How do order patterns vary across weekdays and weekends?
SELECT 
    DAYOFWEEK(STR_TO_DATE(order_date, '%Y-%m-%d')) AS weekday_number,
    CASE 
        WHEN DAYOFWEEK(STR_TO_DATE(order_date, '%Y-%m-%d')) IN (1,7) THEN 'Weekend'
        ELSE 'Weekday'
    END AS day_type,
    COUNT(o.ord_id) AS total_orders,
    SUM(od.total_price) AS total_revenue
FROM orders o
JOIN order_details od ON o.ord_id = od.ord_id
GROUP BY day_type, weekday_number
ORDER BY weekday_number;

